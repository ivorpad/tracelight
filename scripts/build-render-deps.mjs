// Rebuild the code-history renderer's vendored dependencies after bumping handlebars or shiki:
//   node scripts/build-render-deps.mjs
// The output is committed: the skill is used from a checkout and from the vsix, and neither runs npm.
import * as esbuild from 'esbuild';
import { readFileSync } from 'node:fs';

const version = (name) => JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8')).version;
// skills/pyokka gets Python; skills/tracelight gets JavaScript, TypeScript and TSX as well.
const bundles = [
  ['scripts/render-deps.entry.mjs', 'skills/pyokka/scripts/render-deps.cjs'],
  ['scripts/render-deps.tracelight.entry.mjs', 'skills/tracelight/scripts/render-deps.cjs'],
];
for (const [entry, outfile] of bundles) {
  await esbuild.build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    minify: true,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    legalComments: 'eof',
    banner: { js: `// Generated by scripts/build-render-deps.mjs (handlebars ${version('handlebars')}, shiki ${version('shiki')}). Do not edit.` },
    logLevel: 'info',
  });
}
